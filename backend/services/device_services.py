def delete_device_service(
    current_user_id,
    current_username,
    device_id
):
    """
    Responsibility:
        Soft delete a registered device.

    Business Rules:
        • Only authenticated users may delete devices.
        • Device must exist.
        • Device must not already be deleted.
        • Soft delete by setting deleted = 1.
        • Record deletion timestamp.
        • Record the action in the audit log.

    Returns:
        Success or error response.
    """

    connection = get_db_connection()

    cursor = connection.cursor()

    # Check device exists
    cursor.execute(
        """
        SELECT *
        FROM devices
        WHERE id = ?
        """,
        (device_id,)
    )

    device = cursor.fetchone()

    if not device:

        connection.close()

        return {
            "status": "error",
            "message": "Device not found."
        }, 404

    # Already deleted?
    if device["deleted"] == 1:

        connection.close()

        return {
            "status": "error",
            "message": "Device has already been deleted."
        }, 400

    timestamp = (
        datetime.now(timezone.utc)
        .isoformat()
        .replace("+00:00", "Z")
    )

    # Soft delete
    cursor.execute(
        """
        UPDATE devices
        SET
            deleted = 1,
            deleted_at = ?
        WHERE id = ?
        """,
        (
            timestamp,
            device_id
        )
    )

    connection.commit()

    # Audit log
    log_activity(
        current_user_id,
        current_username,
        f"Deleted device '{device['hostname']}'"
    )

    connection.close()

    return {
        "status": "success",
        "message": "Device deleted successfully."
    }, 200