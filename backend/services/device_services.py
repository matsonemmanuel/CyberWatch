def update_device_service(
    device_id,
    current_user_id,
    current_username,
    data
):
    """
    Responsibility:
        Update an existing registered device.

    Business Rules:
        • Only authenticated users may update devices.
        • Device must exist.
        • Hostname is required.
        • IP address is required.
        • Operating system is required.
        • Status is required.
        • IP address must be valid.
        • IP address must remain unique.
        • Status must be one of the allowed device statuses.
        • Record the update in the audit log.

    Returns:
        Updated device information.
    """

    hostname = data.get("hostname")
    ip_address = data.get("ip_address")
    operating_system = data.get("operating_system")
    status = data.get("status")

    # Required fields
    if not hostname or not ip_address or not operating_system or not status:

        return {
            "status": "error",
            "message": "Hostname, IP address, operating system and status are required."
        }, 400

    # Validate IP Address
    try:

        ipaddress.ip_address(ip_address)

    except ValueError:

        return {
            "status": "error",
            "message": "Invalid IP address."
        }, 400

    # Validate status
    if status not in ALLOWED_DEVICE_STATUSES:

        return {
            "status": "error",
            "message": "Invalid device status."
        }, 400

    connection = get_db_connection()

    cursor = connection.cursor()

    # Check device exists
    cursor.execute(
        """
        SELECT *
        FROM devices
        WHERE id = ?
        """,
        (device_id,)
    )

    existing_device = cursor.fetchone()

    if not existing_device:

        connection.close()

        return {
            "status": "error",
            "message": "Device not found."
        }, 404

    # Ensure IP address is unique (excluding this device)
    cursor.execute(
        """
        SELECT id
        FROM devices
        WHERE ip_address = ?
        AND id != ?
        """,
        (
            ip_address,
            device_id
        )
    )

    duplicate_ip = cursor.fetchone()

    if duplicate_ip:

        connection.close()

        return {
            "status": "error",
            "message": "IP address already exists."
        }, 409

    # Update the device
    cursor.execute(
        """
        UPDATE devices
        SET
            hostname = ?,
            ip_address = ?,
            operating_system = ?,
            status = ?
        WHERE id = ?
        """,
        (
            hostname,
            ip_address,
            operating_system,
            status,
            device_id
        )
    )

    connection.commit()

    # Retrieve updated device
    cursor.execute(
        """
        SELECT *
        FROM devices
        WHERE id = ?
        """,
        (device_id,)
    )

    updated_device = cursor.fetchone()

    connection.close()

    # Audit Log
    log_activity(
        current_user_id,
        current_username,
        f"Updated device '{hostname}'"
    )

    return {
        "status": "success",
        "message": "Device updated successfully.",
        "device": {
            "id": updated_device["id"],
            "hostname": updated_device["hostname"],
            "ip_address": updated_device["ip_address"],
            "operating_system": updated_device["operating_system"],
            "status": updated_device["status"],
            "registered_at": updated_device["registered_at"]
        }
    }, 200


